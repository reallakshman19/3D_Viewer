import assert from 'node:assert/strict';
import { applyXmlCompareCanvasAction, createXmlCompareCanvasState } from '../xml-compare/XmlCompareCanvasStateController.js';
import { createXmlCompareWorkspaceModel } from '../xml-compare/XmlCompareWorkspaceModel.js';
import { renderXmlCompareWorkspaceShellHtml } from '../xml-compare/XmlCompareWorkspaceShell.js';

let state=createXmlCompareCanvasState();
state=applyXmlCompareCanvasAction(state,{type:'set-mode',side:'source',mode:'orbit'});
assert.equal(state.source.mode,'orbit');
state=applyXmlCompareCanvasAction(state,{type:'fit-all',side:'target',records:[{position:{x:1,y:2,z:3}}]});
assert.equal(state.fitCommands.target.ok,true);
const beforeValidation=state;
state=applyXmlCompareCanvasAction(state,{type:'set-validation-layer',layer:'node'});
assert.equal(state.validation.layer,'node');
assert.equal(beforeValidation.validation.layer,'current');
const afterLayer=state;
state=applyXmlCompareCanvasAction(state,{type:'set-validation-tolerance-mm',toleranceMm:'2.5'});
assert.equal(state.validation.toleranceMm,2.5);
assert.equal(afterLayer.validation.toleranceMm,1);
const report={datasets:{A:{componentCount:1,components:[{id:'A-1',type:'PIPE',label:'Pipe A',pipelineRef:'L1',points:[{x:0,y:0,z:0}]}]},B:{componentCount:1,components:[{id:'B-1',type:'PIPE',label:'Pipe B',pipelineRef:'L1',points:[{x:1000,y:0,z:0}]}]}},topologyIssues:{summary:{issueCount:0},issues:[]},parseErrors:[]};
state=applyXmlCompareCanvasAction(state,{type:'hover-record',side:'source',uid:'A-1',records:[{uid:'A-1',position:{x:0,y:0,z:0}}]});
state=applyXmlCompareCanvasAction(state,{type:'select-record',side:'source',uid:'A-1',records:[{uid:'A-1',lineNo:'L1',position:{x:0,y:0,z:0}}]});
state=applyXmlCompareCanvasAction(state,{type:'select-record',side:'target',uid:'B-1',records:[{uid:'B-1',lineNo:'L1',position:{x:1000,y:0,z:0}}]});
assert.equal(state.source.hoveredUid,'A-1');
assert.equal(state.source.selectedUid,'A-1');
assert.equal(state.target.selectedUid,'B-1');
assert.equal(state.autoMapRequest,null);
state=applyXmlCompareCanvasAction(state,{type:'add-compare-field',field:'globalX'});
state=applyXmlCompareCanvasAction(state,{type:'add-compare-field',field:'globalY'});
state=applyXmlCompareCanvasAction(state,{type:'add-compare-field',field:'globalX'});
assert.deepEqual(state.compareFields,['globalX','globalY']);
state=applyXmlCompareCanvasAction(state,{type:'remove-compare-field',field:'globalY'});
assert.deepEqual(state.compareFields,['globalX']);
state=applyXmlCompareCanvasAction(state,{type:'add-compare-field',field:'globalZ'});
state=applyXmlCompareCanvasAction(state,{type:'request-auto-map',scope:'node'});
assert.equal(state.autoMapRequest.scope,'node');
assert.equal(state.autoMapRequest.sourceUid,'A-1');
assert.equal(state.autoMapRequest.targetUid,'B-1');
assert.equal(state.autoMapRequest.validationLayer,'node');
assert.equal(state.autoMapRequest.toleranceMm,2.5);
assert.deepEqual(state.autoMapRequest.compareFields,['globalX','globalZ']);
const model=createXmlCompareWorkspaceModel({report,canvasState:state});
assert.equal(model.source.records.length,1);
assert.deepEqual(model.compareFields,['globalX','globalZ']);
assert.equal(model.navStates.source.mode,'orbit');
const html=renderXmlCompareWorkspaceShellHtml(model);
assert.match(html,/data-xml-compare-nav-mode="orbit" class="is-active"/);
assert.match(html,/data-xml-compare-record-uid="A-1"/);
assert.match(html,/Auto Map Selected/);
assert.doesNotMatch(html,/Auto Map Selected Node/);
assert.doesNotMatch(html,/Auto Map Selected Line/);
assert.match(html,/globalX/);
assert.match(html,/globalZ/);
assert.match(html,/Applicable Hierarchy Layer/);
assert.match(html,/Coordinate tolerance/);
assert.match(html,/value="2.5"/);
console.log('xml-compare-canvas-state-activation: all assertions passed');
